Map::Map(SDL_Renderer* ren): renderer(ren)
{
    dirt = TextureManager::LoadTexture("/images/dirt.png", ren);
    grass = TextureManager::LoadTexture("/images/grass.png", ren);
    water = TextureManager::LoadTexture("/images/water.png", ren);

    loadMap(lvl1);

    srcRect.x = srcRect.y = 0;
    srcRect.w = destRect.w = 32;
    srcRect.h = destRect.h = 32;

    destRect.x = destRect.y = 0;
}

void Map::loadMap(int arr[20][25])
{
    for (int row = 0; row < 20; row++)
    {
        for (int column = 0; column < 25; column++)
        {
            map[row][column] = arr[row][column];
        }
    }
}

void Map::render()
{
    int type = 0;

    for (int row = 0; row < 20; row++)
    {
        for (int column = 0; column < 25; column++)
        {
            type = map[row][column];

            destRect.x = column * 32;
            destRect.y = row * 32;

            destRect.x = column * 32;
            destRect.y = row * 32;

            switch (type)
            {
            case 0:
                TextureManager::Render(renderer, water, srcRect, destRect);
                break;
            case 1:
                TextureManager::Render(renderer, dirt, srcRect, destRect);
                break;
            case 2:
                TextureManager::Render(renderer, grass, srcRect, destRect);
                break;
            default:
                break;
            }
        }
    }
}